export function obtenerMesasOficialesColegio(nombreColegio) {
  if (!nombreColegio) return 0;
  const norm = (s) => (s || "").toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/[^a-z0-9]/g, "");
  const target = norm(nombreColegio);
  if (MESAS_POR_COLEGIO_OFICIAL[nombreColegio]) return MESAS_POR_COLEGIO_OFICIAL[nombreColegio];
  for (const [col, mesas] of Object.entries(MESAS_POR_COLEGIO_OFICIAL)) {
    const cNorm = norm(col);
    if (cNorm === target || cNorm.includes(target) || target.includes(cNorm)) {
      return mesas;
    }
  }
  return 0;
}
